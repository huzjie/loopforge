"""LoopForge DTO 层 —— 全部对外契约的唯一入口。

分层约定
--------

* ``*Create`` / ``*Update`` / ``*Request``：**入参**模型，继承
  :class:`~loopforge.schemas.common.LFModel`，``extra="forbid"``，
  拼错字段直接 422 而不是被静默吞掉。
* ``*Read`` / ``*Detail`` / ``*Result``：**出参**模型，继承
  :class:`~loopforge.schemas.common.ORMModel`，``from_attributes=True``，
  可以直接从 ORM 对象构造。
* ``*Query``：查询条件模型，字段全部可选。

下游 WP 只需 ``from loopforge.schemas import XxxCreate``，
不要深入到具体子模块 —— 子模块拆分属于内部实现细节。
"""

